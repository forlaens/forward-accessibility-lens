export function normalizeLanguagePreference(value) {
  return value === "system" || SUPPORTED_CODES.has(String(value)) ? String(value) : DEFAULT_LANGUAGE_PREFERENCE;
}

export function resolvePluginLanguage(preference, languages = []) {
  const normalized = normalizeLanguagePreference(preference);
  if (normalized !== "system") {
    return normalized;
  }

  for (const language of languages) {
    const code = normalizeLanguageCode(language);
    if (SUPPORTED_CODES.has(code)) {
      return code;
    }
  }

  return "en";
}

export function getNavigatorLanguages() {
  if (globalThis.navigator?.languages?.length) {
    return globalThis.navigator.languages;
  }

  return [globalThis.navigator?.language ?? ""];
}

export function t(language, key, values = {}) {
  const dictionary = dictionaries[language] ?? dictionaries.en;
  const template = dictionary[key] ?? dictionaries.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export function formatCount(language, count, keyPrefix) {
  const suffix = count === 1 ? "one" : "other";
  return `${count} ${t(language, `${keyPrefix}.${suffix}`)}`;
}

export function getItemWord(language, count) {
  return t(language, count === 1 ? "common.item.one" : "common.item.other");
}

export function formatList(language, items) {
  if (items.length <= 1) {
    return items[0] ?? "";
  }

  try {
    return new Intl.ListFormat(language, { style: "long", type: "conjunction" }).format(items);
  } catch {
    return items.length === 2
      ? items.join(", ")
      : `${items.slice(0, -1).join(", ")}, ${items.at(-1)}`;
  }
}

